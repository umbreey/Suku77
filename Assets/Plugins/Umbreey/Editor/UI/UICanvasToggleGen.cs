using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Umbreey.Editor
{
    /// <summary>
    /// UIGen 期静态判定：哪些 UI 可以用 canvas-toggle 隐藏（而非 SetActive）。
    ///
    /// 挂接：在 UIGen.GenDef() 末尾，紧跟 UIDefGen.Gen(config) 之后调用 UICanvasToggleGen.Gen(config)。
    ///
    /// 为什么扫 DstPrefabPath（Gen 副本）：运行时 Assets.InstantiateAsync 加载的是 UIGen 产物（ReplaceRoot 后的类型）。
    /// 扫 SrcPrefabPath（业务副本）会严重低估风险。
    ///
    /// 安全判定逻辑与 UICanvasToggleValidator 共用 CanvasToggleSafety，不再维护任何按组件类型名写死的名单。
    /// 一个 prefab 可 canvas-toggle ⇔ 它上面每一个自定义 Mono 都“canvas 安全”（详见 CanvasToggleSafety）。
    /// 白名单随组件逐步补偿而自动扩容，终点 = 全部 UI prefab。
    /// 此外 IsCanvasSafe 会自动排除含 SpriteRenderer 的 prefab（普通 Renderer 不受 Canvas.enabled 影响，关 Canvas 仍会绘制），
    /// 并提供 kExcludeUIs 手动排除名单兜底其它「关 Canvas 无效」的非 Canvas 渲染组件。
    ///
    /// Update 驱动的空转组件（如 LoopListView2/GridView）不实现任何生命周期方法，会被 CanvasToggleSafety 误判为安全；
    /// 当前已直接列入 kConfirmedSafeComponents 兜底（若产生性能问题再移出）。
    ///
    /// 调试：Gen 时除生成白名单 .cs 外，把“未进白名单的 UI 名称 + 被排除原因”写到 kExcludedLogFileName。
    /// </summary>
    public static class UICanvasToggleGen
    {
        private const string kFileName = "UICanvasToggleDef";
        private const string kCopyright = "// This code is generated by Umbreey. Do not modify it directly.";
        // 单独的排除明细日志（与生成的 .cs 同目录，.log 不会被编译）
        private const string kExcludedLogFileName = "UICanvasToggleDef.Excluded.log";

        // B 类（UIImage/UIText/UITextMeshPro）资源常驻持有是净收益，不做排除（由 CanvasToggleSafety 判良性）。

        private const bool kExcludeAnimation = false; // Animation/Animator 已放开，分支不触发；保留以便回滚

        /// <summary>
        /// 用户自定义排除名单：名单中的 UI 整树强制走默认 SetActive，不进 canvas-toggle 白名单。
        /// 用于「关闭 Canvas 无效」的 UI——典型是含 SpriteRenderer（普通 Renderer，不受 Canvas.enabled 影响，
        /// 关掉后 Sprite 仍会被常规渲染管线画出来）。SpriteRenderer 已由 IsCanvasSafe 自动检测，本名单主要兜其它非 Canvas 渲染组件。
        /// </summary>
        private static readonly HashSet<string> kExcludeUIs = new HashSet<string>
        {
            // "UIFoo", "UIBar",
        };

        /// <summary>白名单生成所需的 UIGen 配置（与 UIGen.GenDef 一致，供校验器后编译复检复用）。</summary>
        public static UIGen.Config GetConfig()
        {
            return new UIGen.Config()
            {
                BasePath = "Assets/HotUpdate/UI",
                SrcPrefabPath = "Assets/AssetBundles/UI/Prefab",
                DstPrefabPath = "Assets/AssetBundles/UI/Prefab/Gen",
            };
        }

        /// <summary>Gen 报告：白名单 + 被排除明细（ui 名 -> 原因列表）。供 Gen 写文件/日志、校验器复检共用。</summary>
        public sealed class Report
        {
            public readonly List<string> Whitelist = new List<string>();
            public readonly Dictionary<string, List<string>> Excluded = new Dictionary<string, List<string>>();
        }

        /// <summary>计算应进入 canvas-toggle 白名单的 UI 名列表（与 Gen 写文件共用；供校验器后编译复检复用）。</summary>
        public static List<string> ComputeWhitelist(UIGen.Config config)
        {
            return ComputeReport(config).Whitelist;
        }

        /// <summary>计算完整报告：白名单 + 每个被排除 UI 的原因明细。</summary>
        public static Report ComputeReport(UIGen.Config config)
        {
            string targetDirectory = config.DstPrefabPath; // Gen 副本
            var report = new Report();
            if (string.IsNullOrEmpty(targetDirectory) || !Directory.Exists(targetDirectory))
                return report;

            int total = 0;
            foreach (string prefabPath in GetAllPrefabsInDirectory(targetDirectory))
            {
                GameObject prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
                if (prefab == null || !prefab.name.StartsWith("UI")) continue;
                total++;
                var reasons = new List<string>();
                if (IsCanvasSafe(prefab, reasons))
                    report.Whitelist.Add(prefab.name);
                else
                    report.Excluded[prefab.name] = reasons;
            }
            report.Whitelist.Sort();
            return report;
        }

        public static void Gen(UIGen.Config config)
        {
            var report = ComputeReport(config);
            if (report.Whitelist.Count == 0)
            {
                Debug.LogWarning($"[UICanvasToggleGen] DstPrefabPath 无效或无 UI prefab，跳过白名单生成。");
            }

            string file = $"{config.BasePath}/{kFileName}.cs";
            StringBuilder sb = new StringBuilder();
            sb.AppendLine(kCopyright);
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using Umbreey;");
            sb.AppendLine($"public class {kFileName}");
            sb.AppendLine("{");
            sb.AppendLine("\t/// <summary>允许使用 canvas-toggle 隐藏模式的 UI 名单（UIGen 静态判定生成，不可手改；跑 UIGen 后填充）</summary>");
            sb.AppendLine("\tpublic static readonly List<string> Names = new List<string>");
            sb.AppendLine("\t{");
            foreach (var name in report.Whitelist)
                sb.AppendLine($"\t\t\"{name}\",");
            sb.AppendLine("\t};");
            sb.AppendLine();
            sb.AppendLine("\tprivate static readonly HashSet<string> s_Set = new HashSet<string>(Names);");
            sb.AppendLine("\tpublic static bool Contains(string name) => s_Set.Contains(name);");
            sb.AppendLine("\t/// <summary>注册到 UIManager（跨程序集：HotUpdate → Umbreey 单向引用，本文件位于 HotUpdate asm）</summary>");
            sb.AppendLine("\tpublic static void Register() => UIManager.RegCanvasToggleWhitelist(Names);");
            sb.AppendLine("}");
            sb.AppendLine(kCopyright);
            string dir = Path.GetDirectoryName(file);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
                Directory.CreateDirectory(dir);
            File.WriteAllText(file, sb.ToString());
            Debug.Log($"[UICanvasToggleGen] 白名单生成完成：{report.Whitelist.Count} 个 UI -> {file}");

            // 单独的排除明细日志（未进白名单的 UI 名称 + 原因）
            string logFile = $"{config.BasePath}/{kExcludedLogFileName}";
            string logDir = Path.GetDirectoryName(logFile);
            if (!string.IsNullOrEmpty(logDir) && !Directory.Exists(logDir))
                Directory.CreateDirectory(logDir);
            WriteExcludedLog(logFile, config, report);
            Debug.Log($"[UICanvasToggleGen] 被排除 UI 明细（{report.Excluded.Count} 个）已写入：{logFile}");

            // 生成后顺带跑安全校验：提示“未知自定义组件 OnDisable 静默失败”的风险
            UICanvasToggleValidator.Validate(config, report.Whitelist);
        }

        /// <summary>把被排除的 UI 名 + 原因写成易读的文本日志文件。</summary>
        private static void WriteExcludedLog(string logFile, UIGen.Config config, Report report)
        {
            int total = report.Whitelist.Count + report.Excluded.Count;
            var sb = new StringBuilder();
            sb.AppendLine("============================================================");
            sb.AppendLine(" UICanvasToggle 白名单排除明细 (UIGen 生成)");
            sb.AppendLine("============================================================");
            sb.AppendLine($" 生成时间 : {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine($" 扫描目录 : {config.DstPrefabPath}");
            sb.AppendLine($" 总 UI 数 : {total} | 进入白名单 : {report.Whitelist.Count} | 被排除 : {report.Excluded.Count}");
            sb.AppendLine();

            // 原因分类统计
            int cUncompensated = 0, cSubpage = 0, cAnim = 0, cForce = 0, cMissing = 0, cSprite = 0, cCustom = 0;
            // 未补偿组件去重清单：从“组件 X 未补偿”原因中提取类型名，便于一眼看清差在哪
            var uncompensatedComps = new HashSet<string>();
            foreach (var reasons in report.Excluded.Values)
            {
                foreach (var r in reasons)
                {
                    if (r.Contains("未补偿"))
                    {
                        cUncompensated++;
                        // 原因形如：组件 {Type.Name} 未补偿 (...)
                        const string kPrefix = "组件 ", kSuffix = " 未补偿";
                        int s = r.IndexOf(kPrefix, StringComparison.Ordinal);
                        int e = r.IndexOf(kSuffix, StringComparison.Ordinal);
                        if (s >= 0 && e > s + kPrefix.Length)
                            uncompensatedComps.Add(r.Substring(s + kPrefix.Length, e - (s + kPrefix.Length)));
                    }
                    else if (r.Contains("子页面")) cSubpage++;
                    else if (r.Contains("Animation") || r.Contains("Animator")) cAnim++;
                    else if (r.Contains("强制排除")) cForce++;
                    else if (r.Contains("Missing Script")) cMissing++;
                    else if (r.Contains("SpriteRenderer")) cSprite++;
                    else if (r.Contains("自定义排除名单")) cCustom++;
                }
            }
            sb.AppendLine("--- 排除原因统计 ---");
            sb.AppendLine($" 未补偿组件(有生命周期逻辑但无 IUIVisibleNotify/不在安全白名单内) : {cUncompensated}");
            // 在开头列出所有未补偿组件名称（去重），对齐参考下方明细快速定位
            sb.AppendLine($"   涉及组件 (去重, 共 {uncompensatedComps.Count} 种):");
            if (uncompensatedComps.Count > 0)
            {
                var compList = new List<string>(uncompensatedComps);
                compList.Sort();
                // 每行最多约 90 字符换行，避免单行过长
                var line = new StringBuilder();
                foreach (var comp in compList)
                {
                    string token = (line.Length == 0 ? comp : ", " + comp);
                    if (line.Length + token.Length > 90 && line.Length > 0)
                    {
                        sb.AppendLine($"     {line}");
                        line.Clear().Append(comp);
                    }
                    else
                    {
                        line.Append(token);
                    }
                }
                if (line.Length > 0) sb.AppendLine($"     {line}");
            }
            else
            {
                sb.AppendLine("     (无)");
            }
            sb.AppendLine($" 含子页面 p_ 节点                                                            : {cSubpage}");
            sb.AppendLine($" 含 Animation/Animator                                                       : {cAnim}");
            sb.AppendLine($" 强制排除 F 类 (LoopListView2/LoopGridView, Update 驱动)                       : {cForce}");
            sb.AppendLine($" Missing Script (脚本丢失)                                                    : {cMissing}");
            sb.AppendLine($" 含 SpriteRenderer (Canvas.enabled 无法隐藏, 须走 SetActive)                     : {cSprite}");
            sb.AppendLine($" 自定义排除名单 kExcludeUIs                                              : {cCustom}");
            sb.AppendLine();

            sb.AppendLine($"--- 被排除 UI 列表 ({report.Excluded.Count}) ---");
            sb.AppendLine();
            // 按 UI 名排序输出，便于对照
            var sorted = new List<string>(report.Excluded.Keys);
            sorted.Sort();
            foreach (var uiName in sorted)
            {
                sb.AppendLine($"[{uiName}]");
                foreach (var reason in report.Excluded[uiName])
                    sb.AppendLine($"  · {reason}");
                sb.AppendLine();
            }
            File.WriteAllText(logFile, sb.ToString());
        }

        private static bool IsCanvasSafe(GameObject prefab, List<string> reasons)
        {
            bool safe = true;

            // 0) 用户自定义排除名单：名单中的 UI 整树强制走 SetActive（已知关闭 Canvas 无效）
            if (kExcludeUIs.Contains(prefab.name))
            {
                reasons.Add("在自定义排除名单 kExcludeUIs 中 (手动排除, 用户已知关闭 Canvas 无效的 UI)");
                safe = false;
            }

            // 1) 组件安全扫描：所有自定义 Mono 都必须 canvas 安全，否则整 prefab 出局
            var comps = prefab.GetComponentsInChildren<MonoBehaviour>(true);
            foreach (var c in comps)
            {
                if (c == null) { reasons.Add("含 Missing Script (GetComponents 返回 null)"); safe = false; continue; }
                var type = c.GetType();
                if (!CanvasToggleSafety.IsComponentCanvasSafe(type))
                {
                    reasons.Add($"组件 {type.Name} 未补偿 (有 OnDisable/OnEnable 但未实现 IUIVisibleNotify / 不在确认安全类型白名单内)");
                    safe = false;
                }
            }

            // 3) Missing Script 兜底（GetComponents 可能漏检，用编辑器 API 确认）
            bool hasMissingReason = false;
            foreach (var r in reasons) if (r.Contains("Missing Script")) { hasMissingReason = true; break; }
            if (!hasMissingReason)
            {
                foreach (var go in prefab.GetComponentsInChildren<Transform>(true))
                {
                    if (GameObjectUtility.GetMonoBehavioursWithMissingScriptCount(go.gameObject) > 0)
                    {
                        reasons.Add("含 Missing Script (编辑器 API 检测)");
                        safe = false;
                        break;
                    }
                }
            }

            // 4) Animation/Animator 已放开，分支不触发；保留以便回滚
            if (kExcludeAnimation)
            {
                if (prefab.GetComponentsInChildren<Animation>(true).Length > 0)
                {
                    reasons.Add("含 Animation 组件 (kExcludeAnimation=true)");
                    safe = false;
                }
                if (prefab.GetComponentsInChildren<Animator>(true).Length > 0)
                {
                    reasons.Add("含 Animator 组件 (kExcludeAnimation=true)");
                    safe = false;
                }
            }
            // 5) SpriteRenderer：普通 Renderer，不受 Canvas.enabled 影响，canvas-toggle 关闭后 Sprite 仍会绘制
            if (prefab.GetComponentsInChildren<SpriteRenderer>(true).Length > 0)
            {
                reasons.Add("含 SpriteRenderer (普通 Renderer, Canvas.enabled 无法隐藏, 必须走 SetActive)");
                safe = false;
            }
            return safe;
        }

        // 目录遍历（扫的就是 Gen 目录，因此不跳过含 "Gen" 的路径）
        private static List<string> GetAllPrefabsInDirectory(string directory)
        {
            List<string> paths = new List<string>();
            DepthFirstSearch(directory, paths);
            return paths;
        }
        private static void DepthFirstSearch(string dir, List<string> outPaths)
        {
            outPaths.AddRange(Directory.GetFiles(dir, "*.prefab", SearchOption.TopDirectoryOnly));
            foreach (var sub in Directory.GetDirectories(dir, "*", SearchOption.TopDirectoryOnly))
                DepthFirstSearch(sub, outPaths);
        }
    }
