using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Umbreey.Editor
{
    public class UIDefGen
    {
        private class GenPrefab
        {
            public string PrefabName;
            public int SortingOrder;
        }

        private static string UIDef = "UIDef";
        private static int MaxNameLength = 27;
        public static void Gen(UIGen.Config config)
        {
            var kCopyright = @"// This code is generated by Umbreey. Do not modify it directly.";
            string targetDirectory = config.SrcPrefabPath; // 指定目录
            List<string> prefabPaths = GetAllPrefabsInDirectory(targetDirectory);

            string file = $"{config.BasePath}/{UIDef}.cs";
            StringBuilder sb = new StringBuilder();
            sb.AppendLine(kCopyright);
            sb.AppendLine($"using System.Collections;");
            sb.AppendLine($"using System.Collections.Generic;");
            sb.AppendLine($"using UnityEngine;");
            sb.AppendLine($"using Umbreey;");
            sb.AppendLine($"public class {UIDef}");
            sb.AppendLine("{");
            
            Dictionary<string, List<GenPrefab>> genPrefabDict = new Dictionary<string, List<GenPrefab>>();
            List<GenPrefab> genPrefabs = new List<GenPrefab>();
            foreach (string prefabPath in prefabPaths)
            {
                if(prefabPath.Contains("Gen")) continue;
                GameObject prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
                if (prefab == null || !prefab.name.StartsWith("UI")) continue;

                var parentDir = Path.GetDirectoryName(prefabPath)?.Replace('\\','/').Replace(targetDirectory, "").Trim('/','\\');
                
                Canvas canvas = prefab.GetComponent<Canvas>(); // 查找Canvas组件
                if (canvas != null)
                {
                    if (string.IsNullOrEmpty(parentDir))
                    {
                        genPrefabs.Add(new GenPrefab()
                        {
                            PrefabName = prefab.name,
                            SortingOrder = canvas.sortingOrder,
                        });
                    }
                    else
                    {
                        if (!genPrefabDict.ContainsKey(parentDir))
                        {
                            genPrefabDict.Add(parentDir, new List<GenPrefab>());
                        }
                        
                        genPrefabDict[parentDir].Add(new GenPrefab()
                        {
                            PrefabName = prefab.name,
                            SortingOrder = canvas.sortingOrder,
                        });
                    }
                }
            }
            // 生成子目录下的prefab
            foreach (var kv in genPrefabDict)
            {
                kv.Value.Sort((a, b) => a.SortingOrder.CompareTo(b.SortingOrder));
                sb.AppendLine($"#region {kv.Key}");
                foreach (var genPrefab in kv.Value)
                {
                    sb.AppendLine(GenLine(genPrefab));
                }
                sb.AppendLine($"#endregion\n");
            }
            
            // 生成根目录下的prefab
            genPrefabs.Sort((a, b) => a.SortingOrder.CompareTo(b.SortingOrder));
            foreach (var genPrefab in genPrefabs)
            {
                sb.AppendLine(GenLine(genPrefab));
            }
            
            sb.AppendLine("}");
            sb.AppendLine(kCopyright);
            string dir = Path.GetDirectoryName(file);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
                Directory.CreateDirectory(dir);
            File.WriteAllText(file, sb.ToString());
        }

        private static List<string> GetAllPrefabsInDirectory(string directory)
        {
            List<string> prefabPaths = new List<string>();
            if (!Directory.Exists(directory)) return prefabPaths;

            // 使用自定义深度优先搜索替代Directory.GetFiles
            DepthFirstSearchPrefabs(directory, prefabPaths);

            return prefabPaths;
        }

        /// <summary>
        /// 执行深度优先搜索查找所有prefab文件
        /// </summary>
        /// <param name="directory">起始目录</param>
        /// <param name="prefabPaths">存储结果的列表</param>
        private static void DepthFirstSearchPrefabs(string directory, List<string> prefabPaths)
        {
            // 1. 先获取当前目录下的所有prefab文件
            string[] files = Directory.GetFiles(directory, "*.prefab", SearchOption.TopDirectoryOnly);
            prefabPaths.AddRange(files);

            // 2. 然后递归遍历所有子目录
            string[] subDirectories = Directory.GetDirectories(directory, "*", SearchOption.TopDirectoryOnly);
            foreach (string subDir in subDirectories)
            {
                DepthFirstSearchPrefabs(subDir, prefabPaths);
            }
        }

        private static string GenLine(GenPrefab genPrefab)
        {
            genPrefab.PrefabName = genPrefab.PrefabName.Replace(" ", "");
            StringBuilder sb = new StringBuilder();
            sb.Append($"\tpublic const string {genPrefab.PrefabName}");
            int spaceCount = MaxNameLength - genPrefab.PrefabName.Length;
            for (int i = 0; i < spaceCount; i++)
            {
                sb.Append(" ");
            }
            sb.Append($"= \"{genPrefab.PrefabName}\";");
            for (int i = 0; i < spaceCount; i++)
            {
                sb.Append(" ");
            }
            sb.Append($"//SortingOrder {genPrefab.SortingOrder}");
            return sb.ToString();
        }
    }
}